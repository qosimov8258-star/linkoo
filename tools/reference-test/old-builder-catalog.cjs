// Builds lib/old-report/catalog.ts — the models of the old report builder (Конструктор отчетов) with the lists the
// reference prints for each: Колонки, the groupings, the selects of «Быстрый фильтр» and the fields of «Фильтры».
//
//   node tools/reference-test/old-builder-catalog.cjs <config.json> <ui.json>
//
// <config.json>: the reference's own builder configuration (GET …/saas/report_many_config/, read-only).
// <ui.json>: what its page prints per model (the selects of «Быстрый фильтр», the «Что фильтровать» list), read
//            from the page without applying anything. Both files hold the account's data and stay in backups/
//            (git-ignored); only field identifiers, names and hints go into the catalog. A field named after an
//            attribute of the account's clients is not copied: the model gets `clientAttributes` instead and
//            lists the attributes of this app's own clients (Настройки → Атрибуты клиентов).
const fs = require("fs")
const path = require("path")

const [configFile, uiFile] = process.argv.slice(2)
if (!configFile || !uiFile) throw new Error("usage: old-builder-catalog.cjs <config.json> <ui.json>")
const config = JSON.parse(fs.readFileSync(configFile, "utf8"))
const ui = JSON.parse(fs.readFileSync(uiFile, "utf8"))

const clean = (text) => String(text ?? "").replace(/\s+/g, " ").trim()
const isClientAttribute = (field) => /^market_cache_field_\d+$/.test(field.key)

const models = []
const seenModels = new Set()
for (const [index, model] of config.entries()) {
  // The reference lists one model twice (the same key and lists).
  if (seenModels.has(model.model)) continue
  seenModels.add(model.model)
  const page = ui[index]
  if (!page || clean(page.name) !== clean(model.name)) throw new Error(`no page capture of model #${index} ${model.name}`)
  const quickLabels = new Set((page.quick?.fields ?? []).map((field) => clean(field.label)))
  const compareLabels = new Set((page.filterRow?.selects?.[0]?.options ?? []).map(clean))

  const unique = (fields) => {
    // The page keeps the first field of a repeated identifier.
    const ids = new Set()
    return fields.filter((field) => (ids.has(field.key) ? false : ids.add(field.key)))
  }
  const entry = (field) => {
    const item = [field.key, clean(field.name)]
    if (field.description) item.push(clean(field.description))
    return item
  }
  const columns = unique(model.fields.filter((field) => field.show_in_select))
  const groupFields = unique(model.fields.filter((field) => field.show_in_group))
  const attributeAt = groupFields.findIndex(isClientAttribute)
  const groups = groupFields.filter((field) => !isClientAttribute(field))
  const filterFields = model.fields.filter((field) => field.show_in_filter)
  const filters = []
  const compare = []
  const usedFilterIds = new Set()
  for (const field of filterFields) {
    const name = clean(field.name)
    // Two filters of one identifier: the second gets a suffix (both are on the page).
    let id = field.key
    for (let n = 2; usedFilterIds.has(id); n++) id = `${field.key}~${n}`
    usedFilterIds.add(id)
    const item = [id, name]
    if (quickLabels.has(name)) filters.push(item)
    else if (compareLabels.has(name)) compare.push(item)
    else throw new Error(`${model.name}: the page shows no filter «${name}»`)
  }
  if (filters.length !== (page.quick?.fields ?? []).length) throw new Error(`${model.name}: quick filters ${filters.length} ≠ page ${(page.quick?.fields ?? []).length}`)
  if (columns.length !== (page.panels["Колонки"] ?? []).length) throw new Error(`${model.name}: columns ≠ page`)
  if (groupFields.length !== (page.panels["Вертикальная групировка"] ?? []).length) throw new Error(`${model.name}: groupings ≠ page`)
  models.push({
    key: model.model,
    name: clean(model.name),
    columns: columns.map(entry),
    groups: groups.map(entry),
    filters,
    compare,
    ...(attributeAt >= 0 ? { clientAttributes: attributeAt } : {}),
  })
}

const line = (item) => JSON.stringify(item)
const block = (name, list) => (list.length ? `    ${name}: [\n${list.map((item) => `      ${line(item)},`).join("\n")}\n    ],` : `    ${name}: [],`)
const body = models
  .map(
    (model) =>
      `  {\n    key: ${line(model.key)},\n    name: ${line(model.name)},\n${block("columns", model.columns)}\n${block("groups", model.groups)}\n${block("filters", model.filters)}\n${block("compare", model.compare)}${
        model.clientAttributes === undefined ? "" : `\n    clientAttributes: ${model.clientAttributes},`
      }\n  },`,
  )
  .join("\n")

const out = `// GENERATED by tools/reference-test/old-builder-catalog.cjs — do not edit by hand.
//
// The models of the old report builder (Конструктор отчетов) and, for each, what its panels list, in the
// reference's order: the measures of «Колонки», the groupings of «Вертикальная / Горизонтальная групировка», the
// selects of «Быстрый фильтр» and the fields of «Фильтры». A field is [id, name] or [id, name, hint]: the id is the
// reference's own field identifier (saved reports name their fields by it), the name is the Russian text the
// panels print (the i18n key), the hint is the text of its ⓘ.

export type CatalogField = [id: string, name: string, hint?: string]

export type CatalogModel = {
  key: string
  name: string
  columns: CatalogField[]
  groups: CatalogField[]
  /** «Быстрый фильтр»: multi-selects. */
  filters: CatalogField[]
  /** «Фильтры» → «Что фильтровать»: a value compared with the typed one. */
  compare: CatalogField[]
  /** The model also lists the attributes of the clients as groupings, from this position of \`groups\`. */
  clientAttributes?: number
}

export const OLD_REPORT_CATALOG: CatalogModel[] = [
${body}
]
`
const target = path.resolve(__dirname, "../../lib/old-report/catalog.ts")
fs.writeFileSync(target, out)
const total = (pick) => models.reduce((sum, model) => sum + pick(model).length, 0)
console.log(`${models.length} models: ${total((m) => m.columns)} columns, ${total((m) => m.groups)} groupings, ${total((m) => m.filters)} quick filters, ${total((m) => m.compare)} comparison filters → ${path.relative(process.cwd(), target)} (${out.length} bytes)`)

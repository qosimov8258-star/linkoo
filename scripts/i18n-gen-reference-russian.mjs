// Generates lib/i18n/reference-russian-texts.ts from crawl results (route -> Russian texts that the reference
// leaves untranslated on that page although they exist in its dictionary). Usage:
//   node scripts/i18n-gen-reference-russian.mjs <uz.json> [<en.json>]
import fs from 'node:fs'
const [uzFile, enFile] = process.argv.slice(2)
const read = (f) => (f && fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : {})
const clean = (d) => Object.fromEntries(Object.entries(d).filter(([r]) => r !== '/about'))
const body = JSON.stringify({ uz: clean(read(uzFile)), en: clean(read(enFile)) }, null, 2)
fs.writeFileSync(new URL('../lib/i18n/reference-russian-texts.ts', import.meta.url),
`// GENERATED by scripts/i18n-gen-reference-russian.mjs from crawls of the reference app (do not edit by hand).
// The reference translates only texts that go through its t(); on these pages it prints the Russian text as is,
// although the same text is in its dictionary. DomTranslator skips these exact strings on the listed routes.
export const REFERENCE_RUSSIAN_TEXTS: Record<"uz" | "en", Record<string, string[]>> = ${body}
`)

/** Label of a referencing table: the module's own wording (`own`) first, then
 * the shared map, else "Другие документы" — never the raw table name. */
export function usageTableLabel(table: string, own?: Record<string, string>): string {
  if (own && Object.hasOwn(own, table)) return own[table]
  return Object.hasOwn(LABELS, table) ? LABELS[table] : OTHER_DOCUMENTS_LABEL
}

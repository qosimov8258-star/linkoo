export function getAnalyticsReport(slug: string) {
  return analyticsReports.find((report) => report.slug === slug)
}

export function getAnalyticsResource(slug: string) {
  return analyticsResources.find((resource) => resource.slug === slug)
}

export function getResourceReports(resource: AnalyticsResource) {
  return resource.reportSlugs
    .map((slug) => getAnalyticsReport(slug))
    .filter((report): report is AnalyticsReport => Boolean(report))
}
